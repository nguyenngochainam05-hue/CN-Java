    private void btnTimActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTimActionPerformed
        // TODO add your handling code here:
        String input = txtN.getText().trim();
        int n;
        try {
            if (input.isEmpty() || input.equals("Nhập N")) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập số N");
                return;
            }
            n = Integer.parseInt(input);
            if (n < 0) {
                JOptionPane.showMessageDialog(this, "N phải >= 0");
                return;
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập số nguyên hợp lệ");
            return;
        }

        btnTim.setEnabled(false);
        progressBar.setIndeterminate(true);
        lblKetQua.setText("Đang tính Fibonacci...");

        SwingWorker<BigInteger, Void> worker = new SwingWorker<BigInteger, Void>() {
            @Override
            protected BigInteger doInBackground() {
                Map<Integer, BigInteger> memo = new HashMap<>();
                return fibonacci(n, memo);
            }

            @Override
            protected void done() {
                try {
                    BigInteger result = get();
                    lblKetQua.setText("Fibonacci(" + n + ") = " + result);
                } catch (Exception ex) {
                    lblKetQua.setText("Có lỗi khi tính Fibonacci");
                }
                progressBar.setIndeterminate(false);
                progressBar.setValue(100);
                btnTim.setEnabled(true);
            }
        };

        worker.execute();
    }//GEN-LAST:event_btnTimActionPerformed

       
