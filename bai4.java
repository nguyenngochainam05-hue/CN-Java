private void themPlaceholderChoTxtN() {
        final String placeholder = "Nhập N";
        txtN.setText(placeholder);
        txtN.setForeground(Color.GRAY);

        txtN.addFocusListener(new java.awt.event.FocusAdapter() {
            @Override
            public void focusGained(java.awt.event.FocusEvent evt) {
                if (txtN.getText().equals(placeholder)) {
                    txtN.setText("");
                    txtN.setForeground(Color.BLACK);
                }
            }

            @Override
            public void focusLost(java.awt.event.FocusEvent evt) {
                if (txtN.getText().isEmpty()) {
                    txtN.setText(placeholder);
                    txtN.setForeground(Color.GRAY);
                }
            }
        });
    }
private BigInteger fibonacci(int n, Map<Integer, BigInteger> memo) {
        if (n <= 1) {
            return BigInteger.valueOf(n);
        }

        if (memo.containsKey(n)) {
            return memo.get(n);
        }

        BigInteger value = fibonacci(n - 1, memo).add(fibonacci(n - 2, memo));
        memo.put(n, value);
        return value;
    }
