    private void btnLamMoiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLamMoiActionPerformed
        // TODO add your handling code here:
        int n;
    try {
        n = Integer.parseInt(txtSoMon.getText().trim());
        if (n <= 0) {
            JOptionPane.showMessageDialog(this, "N phải lớn hơn 0");
            return;
        }
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Vui lòng nhập số nguyên hợp lệ cho N");
        return;
    }

    model.setRowCount(0);
    for (int i = 1; i <= n; i++) {
        model.addRow(new Object[]{i, "", ""});
    }
    JOptionPane.showMessageDialog(this, "Đã tạo " + n + " dòng trống.\nChọn từng dòng, nhập Tên môn + Điểm, rồi bấm \"Sửa\" để điền.");
    }//GEN-LAST:event_btnLamMoiActionPerformed

    private void btnThemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnThemActionPerformed
        // TODO add your handling code here:
        int n;
    try {
        n = Integer.parseInt(txtSoMon.getText().trim());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Vui lòng nhập N hợp lệ trước khi thêm môn");
        return;
    }

    if (model.getRowCount() >= n) {
        JOptionPane.showMessageDialog(this, "Đã đủ " + n + " môn, không thể thêm nữa");
        return;
    }

    String tenMon = txtTenMon.getText().trim();
    if (tenMon.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Vui lòng nhập tên môn");
        return;
    }

    Double diemTongKet = docVaTinhDiem();
    if (diemTongKet == null) return;

    int stt = model.getRowCount() + 1;
    model.addRow(new Object[]{stt, tenMon, String.format("%.2f", diemTongKet)});

    txtTenMon.setText("");
    txtChuyenCan.setText("");
    txtGiuaKy.setText("");
    txtCuoiKy.setText("");
    }//GEN-LAST:event_btnThemActionPerformed

    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        // TODO add your handling code here:
        int row = tblMon.getSelectedRow();
    if (row < 0) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 dòng trong bảng để điền/sửa");
        return;
    }

    String tenMon = txtTenMon.getText().trim();
    if (tenMon.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Vui lòng nhập tên môn");
        return;
    }

    Double diemTongKet = docVaTinhDiem();
    if (diemTongKet == null) return;

    model.setValueAt(tenMon, row, 1);
    model.setValueAt(String.format("%.2f", diemTongKet), row, 2);

    txtTenMon.setText("");
    txtChuyenCan.setText("");
    txtGiuaKy.setText("");
    txtCuoiKy.setText("");
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
        int row = tblMon.getSelectedRow();
    if (row < 0) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 dòng trong bảng để xóa");
        return;
    }

    int xacNhan = JOptionPane.showConfirmDialog(this, "Bạn có chắc muốn xóa dòng này?",
            "Xác nhận", JOptionPane.YES_NO_OPTION);
    if (xacNhan == JOptionPane.YES_OPTION) {
        model.removeRow(row);
        danhLaiSTT();
    }
}

private void danhLaiSTT() {
    for (int i = 0; i < model.getRowCount(); i++) {
        model.setValueAt(i + 1, i, 0);
    }
    }//GEN-LAST:event_btnXoaActionPerformed

