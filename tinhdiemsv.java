private Double docVaTinhDiem() {
    double chuyenCan, giuaKy, cuoiKy;
    try {
        chuyenCan = Double.parseDouble(txtChuyenCan.getText().trim());
        giuaKy = Double.parseDouble(txtGiuaKy.getText().trim());
        cuoiKy = Double.parseDouble(txtCuoiKy.getText().trim());
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ và đúng định dạng số cho cả 3 điểm");
        return null;
    }

    if (chuyenCan < 0 || chuyenCan > 10 || giuaKy < 0 || giuaKy > 10 || cuoiKy < 0 || cuoiKy > 10) {
        JOptionPane.showMessageDialog(this, "Các điểm phải trong khoảng 0 đến 10");
        return null;
    }

    return chuyenCan * 0.1 + giuaKy * 0.3 + cuoiKy * 0.6;  
}
