private String dinhDangSo(long so) {
    return NumberFormat.getInstance().format(so);
}
private void gioiHanKyTuMa() {
    txtMa.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {
        @Override
        public void insertUpdate(javax.swing.event.DocumentEvent e) {
            capNhat();
        }

        @Override
        public void removeUpdate(javax.swing.event.DocumentEvent e) {
        }

        @Override
        public void changedUpdate(javax.swing.event.DocumentEvent e) {
            capNhat();
        }

        private void capNhat() {
            SwingUtilities.invokeLater(() -> {
                String text = txtMa.getText();
                if (text.length() > 5) {
                    txtMa.setText(text.substring(0, 5));
                }
            });
        }
    });
    }
private boolean maDaTonTai(String ma, int rowBoQua) {
    for (int i = 0; i < model.getRowCount(); i++) {
        if (i == rowBoQua) continue;
        if (model.getValueAt(i, 0).toString().equalsIgnoreCase(ma)) {
            return true;
        }
    }
    return false;
}
private Object[] docVaKiemTraDuLieu(int rowDangSua) {
    String ma = txtMa.getText().trim();
    String ten = txtTen.getText().trim();
    String soLuongStr = txtSoLuong.getText().trim();

    if (ma.isEmpty() || ten.isEmpty() || soLuongStr.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ Mã, Tên, Số lượng");
        return null;
    }

    if (ma.length() != 5) {
        JOptionPane.showMessageDialog(this, "Mã sản phẩm tối đa 5 ký tự");
        return null;
    }

    if (maDaTonTai(ma, rowDangSua)) {
        JOptionPane.showMessageDialog(this, "Mã sản phẩm đã tồn tại, vui lòng nhập mã khác");
        return null;
    }

    int soLuong;
    try {
        soLuong = Integer.parseInt(soLuongStr);
        if (soLuong <= 0) {
            JOptionPane.showMessageDialog(this, "Số lượng phải lớn hơn 0");
            return null;
        }
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Số lượng phải là số nguyên hợp lệ");
        return null;
    }

    int donGia = soLuong < 10 ? 10000 : 5000;
    long tienHang = (long) soLuong * donGia;

    return new Object[]{
        ma, ten,
        dinhDangSo(soLuong),
        dinhDangSo(donGia),
        dinhDangSo(tienHang)
    };
}
