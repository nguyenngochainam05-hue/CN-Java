    private void btnSuaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSuaActionPerformed
        // TODO add your handling code here:
    int row = tblSanPham.getSelectedRow();
    if (row < 0) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 dòng trong bảng để sửa");
        return;
    }

    Object[] duLieu = docVaKiemTraDuLieu(row);
    if (duLieu == null) return;

    for (int col = 0; col < duLieu.length; col++) {
        model.setValueAt(duLieu[col], row, col);
    }
    xoaONhap();
    }//GEN-LAST:event_btnSuaActionPerformed

    private void btnXoaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnXoaActionPerformed
        // TODO add your handling code here:
    int row = tblSanPham.getSelectedRow();
    if (row < 0) {
        JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 dòng trong bảng để xóa");
        return;
    }

    int xacNhan = JOptionPane.showConfirmDialog(this, "Bạn có chắc muốn xóa sản phẩm này?",
            "Xác nhận", JOptionPane.YES_NO_OPTION);
    if (xacNhan == JOptionPane.YES_OPTION) {
        model.removeRow(row);
        xoaONhap();
    }
    }//GEN-LAST:event_btnXoaActionPerformed
private void xoaONhap() {
    txtMa.setText("");
    txtTen.setText("");
    txtSoLuong.setText("");
}
